 await page.locator('.widget-clock .resize-handle').evaluate(el => el.scrollIntoView({ block: 'center' }));
 await page.waitForTimeout(300);
 const resizer = await page.locator('.widget-clock .resize-handle').boundingBox();
 const oldHeight = after.find(w => w.type === 'clock').position.h;
 await page.mouse.move(resizer.x + 5, resizer.y + 5); await page.mouse.down();
 await page.mouse.move(resizer.x + 5, resizer.y + 115, { steps: 12 }); await page.mouse.up();
 await page.waitForTimeout(400);
 const resized = await page.evaluate(() => JSON.parse(localStorage.getItem('konj-state')).data.instances);
 await page.screenshot({ path: join(tmpdir(), 'konj-resize.png'), fullPage: true });
 if(resized.find(w => w.type === 'clock').position.h === oldHeight) throw Error('Resize did not persist');
 await page.reload(); await page.waitForSelector('.widget');
 const reloaded = await page.evaluate(() => JSON.parse(localStorage.getItem('konj-state')).data.instances);
 if(JSON.stringify(resized) !== JSON.stringify(reloaded)) throw Error('Layout changed after reload');
 await page.getByRole('button', { name: 'افزودن', exact: true }).click();
 await page.getByRole('textbox', { name: 'نام سایت', exact: true }).fill('آزمایش');
 await page.getByRole('textbox', { name: 'آدرس سایت', exact: true }).fill('https://example.com');
 await page.getByRole('button', { name: 'ذخیره', exact: true }).click();
