 await page.getByRole('button', { name: 'چیدمان', exact: true }).click();
 await page.getByRole('button', { name: 'انتقال به بعد', exact: true }).first().click();
 await page.waitForTimeout(300);
 await page.getByRole('button', { name: 'پایان ویرایش', exact: true }).click();
 await page.getByRole('button', { name: 'تنظیمات', exact: true }).click();
 await page.getByRole('textbox', { name: 'چه صدایت کنیم؟' }).fill('سارا');
 await page.getByRole('radio', { name: 'مهِ جنگل' }).check();
 await page.getByRole('checkbox', { name: 'شفافیت کمتر' }).check();
 await page.keyboard.press('Escape');
 await page.reload();
 await page.waitForSelector('.app-shell[data-theme="forest"].opaque');
 if(!await page.getByRole('heading', { level: 1 }).textContent().then(s => s.includes('سارا'))) throw Error('Name persistence failed');
 await page.setViewportSize({ width: 390, height: 844 });
 await page.waitForTimeout(500);
 await page.screenshot({ path: join(tmpdir(), 'konj-mobile.png'), fullPage: true });
