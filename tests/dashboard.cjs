 if(await page.locator('.widget').count() !== 6) throw Error('Undo failed');

 const before = await page.evaluate(() => JSON.parse(localStorage.getItem('konj-state')).data.instances);
 const handle = page.locator('.widget-clock .drag-handle');
 const box = await handle.boundingBox();
